/**
 * Repair prompt text for writer root_write (council defects + hard-validate).
 */

import type { DefectItem, DefectSeverity } from "@okf-wiki/contract";

/** Format defects for writer repair prompts (blocking-only by default). */
export function formatDefectsForRepair(
  defects: readonly DefectItem[],
  options?: { severities?: DefectSeverity[] },
): string {
  const allowed = new Set(options?.severities ?? (["blocking"] as DefectSeverity[]));
  const lines = defects
    .filter((d) => allowed.has(d.severity))
    .map((d) => `- [${d.severity}] ${d.path ?? "?"} ${d.code ?? ""}: ${d.issue}`);
  return lines.join("\n");
}

/** Index structural failures are product-owned; models must not edit index.md for them. */
export function isIndexHardValidateReason(reason: string): boolean {
  return reason.startsWith("indexes:");
}

/** Split hard-validate reasons into product-owned indexes vs writer-repairable. */
export function partitionHardValidateReasons(reasons: readonly string[]): {
  indexReasons: string[];
  writerReasons: string[];
} {
  const indexReasons: string[] = [];
  const writerReasons: string[] = [];
  for (const reason of reasons) {
    if (isIndexHardValidateReason(reason)) indexReasons.push(reason);
    else writerReasons.push(reason);
  }
  return { indexReasons, writerReasons };
}

/**
 * Format mechanical hard-validate reasons as repair instructions for root_write.
 * Strips `indexes:` reasons — multi-level listings are product-regenerated, not model work.
 */
export function hardValidateRepairText(reasons: readonly string[]): string {
  const { writerReasons } = partitionHardValidateReasons(reasons);
  const bullets = writerReasons.map((r) => `- ${r}`).join("\n");
  return [
    "Hard-validate (mechanical) failures — fix these before publish:",
    bullets,
    "",
    "For citation line range out of bounds: re-open the cited source with read/grep,",
    "use only tool-reported 1-based line numbers, and set end ≤ the file's line count.",
    "Never invent or estimate ranges. Prefer edit of the bad Source Citations only.",
    "Do not edit index.md — directory listings are regenerated by the product.",
  ].join("\n");
}
